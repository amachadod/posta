// npm run build:demo
// Runs Posta on the example inbox (fake Gmail, Claude and Linear) and writes docs/data.js for the demo page.
import { writeFileSync, readFileSync, readdirSync } from "node:fs";
import { getConfig } from "../src/config.js";
import { loadSetup, parsePlaybook } from "../src/playbooks.js";
import { runPosta } from "../src/run.js";
import { planTask } from "../src/linear.js";
import { normalizeMessage } from "../src/gmail.js";
import { loadExample, fakeGmail, fakeTriage, fakeLinear, toGmail } from "./examples.js";

const { inbox, triage } = loadExample();
const config = { ...getConfig({}), myName: inbox.me.name, playbook: inbox.playbook };
const setup = loadSetup(config.rootDir, config.playbook);
const gmail = fakeGmail(inbox);
const linear = fakeLinear();
const { briefing, items, waiting } = await runPosta({ config, setup, gmail, linear, triage: fakeTriage(triage), now: new Date(inbox.now), log: () => {} });

const byId = new Map(items.map((i) => [i.email.id, i]));
const emails = inbox.emails.map((raw) => {
  const e = normalizeMessage(toGmail(raw));
  const it = byId.get(e.id);
  const base = { id: e.id, from: e.from, subject: e.subject, date: e.date, body: raw.body, automated: e.automated };
  if (!it) return { ...base, outcome: "prefiltered" };
  const plan = it.triage.task ? planTask(e, it.triage, config) : null;
  return {
    ...base,
    outcome: it.triage.suspicious ? "suspicious" : it.triage.category,
    triage: it.triage,
    task: it.task ? { identifier: it.task.identifier, flagged: plan.flagged, priority: it.triage.task.priority, due: plan.dueDate } : null,
    draft: it.drafted ? it.triage.draft_reply : null,
  };
});

const pbDir = new URL("../playbooks/", import.meta.url);
const order = ["everyone", "account-management", "sales", "marketing", "customer-success"];
const playbooks = readdirSync(pbDir).filter((f) => f.endsWith(".md") && !f.startsWith("_"))
  .map((f) => ({ id: f.replace(/\.md$/, ""), ...parsePlaybook(readFileSync(new URL(f, pbDir), "utf8"), f) }))
  .sort((a, b) => order.indexOf(a.id) - order.indexOf(b.id));

const data = {
  me: inbox.me,
  now: inbox.now,
  playbook: inbox.playbook,
  briefing: { subject: briefing.subject, html: briefing.html, counts: briefing.counts },
  stats: { tasks: linear.created.length, drafts: gmail.calls.drafts.length, sent: gmail.calls.sent.length },
  emails,
  waiting,
  playbooks,
  voice: setup.voice,
};
writeFileSync(new URL("../docs/data.js", import.meta.url), `// Generated by scripts/build-demo.js. Do not edit by hand.\nwindow.POSTA = ${JSON.stringify(data, null, 1)};\n`);
console.log(`Wrote docs/data.js: ${emails.length} emails, ${data.stats.tasks} tasks, ${data.stats.drafts} drafts.`);
